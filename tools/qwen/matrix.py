"""Compare every scenario with the Argon + Claude Sonnet store (data/cases/pilot.csv). No database, no network.
Writes docs/QWEN_COMPARISON.md and data/qwen/matrix.json. Usage: python tools/qwen/matrix.py"""
import csv, json, os, re, collections
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SC = [("q14", "qwen14ic", "Qwen 14B, IndicConformer audio"), ("q14qa", "qwen14qa", "Qwen 14B, Qwen3-ASR 1.7B audio"), ("q4", "qwen4ic", "Qwen 4B, IndicConformer audio")]
MAP = {"MET": "done", "PARTLY": "partly", "NOT_MET": "missed"}; V = {"done": 100, "partly": 50, "missed": 0}
rd = lambda p: {r["conversation_id"]: r for r in csv.DictReader(open(os.path.join(ROOT, p), encoding="utf-8"))}
base = rd("data/cases/pilot.csv")
FIELDS = ["outcome", "reason", "customer_type", "intent", "decision", "quote_given", "test_drive", "stage", "fuel", "product"]
def marks(r):
    m = {}
    for part in (r.get("ai_checks") or "").split(" | "):
        x = re.match(r"(MET|PARTLY|NOT_MET): .*?\((\w+)\)", part)
        if x: m[x.group(2)] = MAP[x.group(1)]
    return m
def words(s): return len(re.findall(r"\S+", s or ""))
out, res = [], {}
for tag, store, label in SC:
    p = os.path.join(ROOT, f"data/cases/{store}.csv")
    rows = rd(f"data/cases/{store}.csv") if os.path.exists(p) else {}
    r = dict(label=label, n=0, marks_eq=0, marks_n=0, score_diff=[], outcome_eq=0, after_ok=0, thin=[], secs=[], flags=0, roles_ok=0, field_eq=collections.Counter(), field_n=collections.Counter(), conv={})
    for cid, b in base.items():
        n = cid.replace("ZC-", ""); ip = os.path.join(ROOT, f"data/qwen/{n}/insights_{tag}.json")
        if not os.path.exists(ip): continue
        q = json.load(open(ip))
        if "error" in q: r["conv"][n] = {"error": True}; continue
        r["n"] += 1; row = rows.get(cid, {})
        sm = marks(b); eq = sum(1 for c in q["checks"] if sm.get(c["id"]) == c["mark"]); mn = sum(1 for c in q["checks"] if c["id"] in sm)
        r["marks_eq"] += eq; r["marks_n"] += mn
        bs = b.get("score"); qs = q.get("score")
        if bs and qs is not None: r["score_diff"].append(abs(int(bs) - qs))
        after_b = (b.get("kind") == "delivery"); r["after_ok"] += int((q["kind"] == "after_booking") == after_b)
        for f in FIELDS:
            if row and (b.get(f) is not None):
                r["field_n"][f] += 1; r["field_eq"][f] += int(str(row.get(f, "")).strip().lower() == str(b.get(f, "")).strip().lower())
        r["flags"] += len(q["review_flags"]); r["secs"].append(q["seconds_taken"])
        r["roles_ok"] += int(not any(x.startswith("roles") for x in q["review_flags"]))
        tp = os.path.join(ROOT, f"data/qwen/{n}/" + ("turns_qasr.json" if tag == "q14qa" else "turns.json"))
        t = json.load(open(tp)); r["thin"].append(t.get("thin_speech_share", 0))
        r["conv"][n] = {"score": qs, "backend": bs or "", "marks": f"{eq}/{mn}", "kind": q["kind"], "outcome": row.get("outcome", ""), "words": sum(words(x["text"]) for x in t["turns"]), "argon_words": words(b.get("transcript")), "flags": q["review_flags"], "reason": row.get("reason", ""), "customer_type": row.get("customer_type", ""), "decision": row.get("decision", ""), "intent": row.get("intent", "")}
    res[tag] = r
json.dump({k: {**v, "field_eq": dict(v["field_eq"]), "field_n": dict(v["field_n"])} for k, v in res.items()}, open(os.path.join(ROOT, "data/qwen/matrix.json"), "w"), indent=1, default=str)
pc = lambda a, b: f"{round(100 * a / b)}%" if b else "-"
L = ["# Open-model scenarios against the Argon + Claude Sonnet store", "", "Generated by `tools/qwen/matrix.py` from the eight pilot recordings. The reference is `data/cases/pilot.csv` (Argon for the transcript and speakers, Claude Sonnet 5.5 for the analysis, plus the dashboard's reading rules and the team's notes). Fields are compared after the same exporter has read both. Conversation #276 has no audio, so seven or eight conversations are compared.", "",
     "## Summary", "", "| Scenario | Conversations | Marks equal | Mean score gap | After-booking found | Roles passed checks | Speech with little or no text | Average time |", "|---|---|---|---|---|---|---|---|"]
for tag, store, label in SC:
    r = res[tag]
    if not r["n"]: L.append(f"| {label} | not run | | | | | | |"); continue
    L.append(f"| {label} | {r['n']} | {pc(r['marks_eq'], r['marks_n'])} | {round(sum(r['score_diff']) / max(1, len(r['score_diff'])))} | {r['after_ok']}/{r['n']} | {r['roles_ok']}/{r['n']} | {round(100 * sum(r['thin']) / len(r['thin']))}% | {round(sum(r['secs']) / len(r['secs']) / 60, 1)} min |")
L += ["", "## Dropdown fields: how often each scenario gives the same value as the Argon + Sonnet store", "", "| Field | " + " | ".join(l for _, _, l in SC) + " |", "|---|" + "---|" * len(SC)]
for f in FIELDS: L.append(f"| {f} | " + " | ".join(pc(res[t]["field_eq"][f], res[t]["field_n"][f]) for t, _, _ in SC) + " |")
L += ["", "## Conversation by conversation", "", "| # | Argon + Sonnet score | " + " | ".join(f"{l} (score, marks equal)" for _, _, l in SC) + " |", "|---|---|" + "---|" * len(SC)]
for cid, b in base.items():
    n = cid.replace("ZC-", "")
    if not any(n in res[t]["conv"] for t, _, _ in SC): continue
    cells = []
    for t, _, _ in SC:
        c = res[t]["conv"].get(n)
        cells.append("-" if not c else "failed" if c.get("error") else ("not scored (after booking)" if c["kind"] == "after_booking" else f"{c['score']} ({c['marks']})"))
    L.append(f"| {n} | {b.get('score') or 'not scored'} | " + " | ".join(cells) + " |")
L += ["", "## Words recovered from the audio", "", "| # | Argon words | " + " | ".join(f"{l}" for _, _, l in SC) + " |", "|---|---|" + "---|" * len(SC)]
for cid, b in base.items():
    n = cid.replace("ZC-", "")
    if not any(n in res[t]["conv"] for t, _, _ in SC): continue
    L.append(f"| {n} | {words(b.get('transcript'))} | " + " | ".join(str(res[t]["conv"].get(n, {}).get("words", "-")) for t, _, _ in SC) + " |")
L += ["", "## What each scenario would show under the dropdowns (counts of conversations)", ""]
for key in ("reason", "customer_type", "decision", "intent", "outcome"):
    L += [f"**{key}**", "", "| Value | Argon + Sonnet | " + " | ".join(l for _, _, l in SC) + " |", "|---|---|" + "---|" * len(SC)]
    vals = collections.Counter(b.get(key, "") or "(blank)" for b in base.values() if b["conversation_id"].replace("ZC-", "") in {n for t, _, _ in SC for n in res[t]["conv"]})
    for t, _, _ in SC:
        for c in res[t]["conv"].values():
            if not c.get("error"): vals.setdefault(c.get(key, "") or "(blank)", 0)
    for v in sorted(vals):
        L.append(f"| {v} | {sum(1 for b in base.values() if (b.get(key, '') or '(blank)') == v and b['conversation_id'].replace('ZC-', '') in {n for t, _, _ in SC for n in res[t]['conv']})} | " + " | ".join(str(sum(1 for c in res[t]["conv"].values() if not c.get("error") and (c.get(key, "") or "(blank)") == v)) for t, _, _ in SC) + " |")
    L.append("")
# How much of the marks agreement is just the commonest answer: a scorer that says "partly" to everything.
ids = {n for t, _, _ in SC for n in res[t]["conv"]}
argon_marks = [m for b in base.values() if b["conversation_id"].replace("ZC-", "") in ids and (b.get("scored") != "no") for m in marks(b).values()]
dist = collections.Counter(argon_marks); top, topn = dist.most_common(1)[0]
L += ["", "## Reading the marks agreement", "", f"Argon + Sonnet marks over the same conversations: " + ", ".join(f"{k} {v}" for k, v in sorted(dist.items())) + f". A scorer that answers \"{top}\" to every check would already match {round(100*topn/len(argon_marks))}%. Anything near that is not evidence of skill; it is the spread of the answers.", "", "| Scenario | done | partly | missed |", "|---|---|---|---|"]
for t, f, l in SC:
    d = collections.Counter(m for r in rd(f"data/cases/{f}.csv").values() if r.get("scored") != "no" for m in marks(r).values())
    L.append(f"| {l} | {d['done']} | {d['partly']} | {d['missed']} |")
L.append(f"| Argon + Sonnet | {dist['done']} | {dist['partly']} | {dist['missed']} |")
open(os.path.join(ROOT, "docs/QWEN_COMPARISON.md"), "w").write("\n".join(L) + "\n"); print("written", {t: res[t]["n"] for t, _, _ in SC})
